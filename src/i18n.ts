export const DICTIONARIES: Record<Lang, Dict> = { "pt-BR": pt, en, "zh-CN": zh, ru, fr, ja, de };

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  // Com sete idiomas, o primeiro recurso passa a ser o inglês: uma chave nova
  // que ainda não foi traduzida aparece legível pra qualquer um, em vez de
  // aparecer em português no meio de uma interface em japonês.
  let str = DICTIONARIES[lang]?.[key] ?? DICTIONARIES.en[key] ?? DICTIONARIES["pt-BR"][key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.split(`{${k}}`).join(String(v));
    }
  }
  return str;
}

