export type Lang = "pt-BR" | "en" | "zh-CN" | "ru" | "fr" | "ja" | "de";

/**
 * A ordem daqui é a ordem do seletor. Cada idioma aparece escrito NO PRÓPRIO
 * idioma, porque quem procura alemão procura "Deutsch", não "German".
 */
export const LANG_LABELS: Record<Lang, string> = {
  "pt-BR": "Português (BR)",
  en: "English",
  "zh-CN": "简体中文",
  ru: "Русский",
  fr: "Français",
  ja: "日本語",
  de: "Deutsch"
};

export const SUPPORTED_LANGS = Object.keys(LANG_LABELS) as Lang[];

/**
 * Primeira execução: em vez de assumir português, tenta o idioma do sistema.
 * O navegador devolve coisas como "pt-BR", "pt", "zh-CN", "zh-Hans-CN" ou
 * "de-AT", então a comparação é por prefixo: casa a etiqueta completa primeiro
 * e depois só a parte do idioma. Sem correspondência, cai no inglês, que é o
 * denominador comum da maior parte dos usuários.
 */
export function detectSystemLang(): Lang {
  const candidatos = typeof navigator !== "undefined" ? navigator.languages ?? [navigator.language] : [];
  for (const bruto of candidatos) {
    if (!bruto) continue;
    const tag = bruto.toLowerCase();
    const exato = SUPPORTED_LANGS.find((c) => c.toLowerCase() === tag);
    if (exato) return exato;
    const base = tag.split("-")[0];
    const porPrefixo = SUPPORTED_LANGS.find((c) => c.toLowerCase().split("-")[0] === base);
    if (porPrefixo) return porPrefixo;
  }
  return "en";
}

